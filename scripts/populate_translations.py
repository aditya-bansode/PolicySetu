path = r"D:\Projects\PolicySetu\app\demo_data.py"
with open(path, "r", encoding="utf-8") as f:
    code = f.read()

# For each policy, insert summary_hi and summary_mr right after summary
for pid, trans in translations_data.items():
    search_str = f'"id": {pid},'
    idx = code.find(search_str)
    if idx != -1:
        sum_idx = code.find('"summary":', idx)
        if sum_idx != -1:
            line_end = code.find('\n', sum_idx)
            # check if summary_hi already present
            next_line = code[line_end+1:line_end+30]
            if '"summary_hi"' not in next_line:
                insertion = f'\n        "summary_hi": "{trans["summary_hi"]}",\n        "summary_mr": "{trans["summary_mr"]}",'
                code = code[:line_end] + insertion + code[line_end:]

with open(path, "w", encoding="utf-8") as f:
    f.write(code)

